"""Database models for the prediction website.

``MatchupPrediction`` mirrors one row of the analysis pipeline's
``matchup_predictions_today.csv``. ``Parlay`` / ``ParlayLeg`` capture the
user-built parlays created from those predictions.
"""

from __future__ import annotations

import json
import math

from django.db import models
from django.urls import reverse

CONFIDENCE_RANK = {"High": 3, "Medium": 2, "Low": 1, "Very low": 0}


def _split_items(text: str) -> list[str]:
    """Turn a stored reasons/risks/warnings field into a clean list of strings."""

    if not text:
        return []
    raw = str(text).strip()
    if not raw:
        return []
    if raw.startswith("[") and raw.endswith("]"):
        try:
            parsed = json.loads(raw)
            if isinstance(parsed, list):
                return [str(part).strip() for part in parsed if str(part).strip()]
        except json.JSONDecodeError:
            pass
    return [part.strip() for part in raw.split(";") if part.strip()]


class MatchupPrediction(models.Model):
    """A single model-generated matchup prediction for one fixture."""

    STATUS_PENDING = "pending"
    STATUS_APPROVED = "approved"
    STATUS_HIDDEN = "hidden"
    STATUS_CHOICES = [
        (STATUS_PENDING, "Pending review"),
        (STATUS_APPROVED, "Approved (public)"),
        (STATUS_HIDDEN, "Hidden"),
    ]

    fixture_id = models.CharField(max_length=255, unique=True)
    sport = models.CharField(max_length=50, blank=True)
    league = models.CharField(max_length=100, blank=True)
    game_date = models.DateTimeField(null=True, blank=True)
    team_a = models.CharField(max_length=120)
    team_b = models.CharField(max_length=120)

    prob_team_a_win = models.FloatField(null=True, blank=True)
    prob_draw = models.FloatField(null=True, blank=True)
    prob_team_b_win = models.FloatField(null=True, blank=True)

    predicted_outcome = models.CharField(max_length=160, blank=True)
    confidence_level = models.CharField(max_length=20, blank=True)
    confidence_score = models.FloatField(null=True, blank=True)
    data_quality = models.CharField(max_length=20, blank=True)

    key_reasons = models.TextField(blank=True)
    main_risks = models.TextField(blank=True)
    data_quality_warnings = models.TextField(blank=True)
    ai_reasoning = models.TextField(
        blank=True,
        help_text="Optional narrative generated by the AI reasoning service.",
    )

    model_version = models.CharField(max_length=80, blank=True)
    status = models.CharField(
        max_length=20, choices=STATUS_CHOICES, default=STATUS_APPROVED
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["game_date", "team_a"]
        indexes = [
            models.Index(fields=["sport", "league"]),
            models.Index(fields=["status"]),
        ]

    def __str__(self) -> str:  # pragma: no cover - trivial
        return f"{self.team_a} vs {self.team_b}"

    def get_absolute_url(self) -> str:
        return reverse("predictions:detail", args=[self.pk])

    # -- Derived helpers -----------------------------------------------------
    @property
    def matchup(self) -> str:
        return f"{self.team_a} vs {self.team_b}"

    @property
    def has_draw(self) -> bool:
        return bool(self.prob_draw)

    @property
    def confidence_rank(self) -> int:
        return CONFIDENCE_RANK.get(self.confidence_level, 0)

    @property
    def reasons_list(self) -> list[str]:
        return _split_items(self.key_reasons)

    @property
    def risks_list(self) -> list[str]:
        return _split_items(self.main_risks)

    @property
    def warnings_list(self) -> list[str]:
        return _split_items(self.data_quality_warnings)

    @property
    def pick_probability(self) -> float | None:
        """Probability the model assigns to its predicted outcome (0-1)."""

        outcome = (self.predicted_outcome or "").lower()
        team_a = (self.team_a or "").lower()
        team_b = (self.team_b or "").lower()
        if "draw" in outcome and self.prob_draw:
            return self.prob_draw
        if team_b and team_b in outcome:
            return self.prob_team_b_win
        if team_a and team_a in outcome:
            return self.prob_team_a_win
        candidates = [
            p for p in (self.prob_team_a_win, self.prob_draw, self.prob_team_b_win)
            if p is not None
        ]
        return max(candidates) if candidates else None

    @property
    def pick_probability_pct(self) -> float | None:
        prob = self.pick_probability
        return round(prob * 100, 1) if prob is not None else None


class Parlay(models.Model):
    """A user-assembled parlay of predicted outcomes from different games."""

    name = models.CharField(max_length=160, blank=True)
    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        verbose_name_plural = "parlays"

    def __str__(self) -> str:  # pragma: no cover - trivial
        return self.name or f"Parlay #{self.pk}"

    def get_absolute_url(self) -> str:
        return reverse("predictions:parlay_detail", args=[self.pk])

    @property
    def leg_count(self) -> int:
        return self.legs.count()

    @property
    def combined_probability(self) -> float | None:
        """Product of leg probabilities (legs assumed independent)."""

        probs = [leg.pick_probability for leg in self.legs.all() if leg.pick_probability]
        if not probs:
            return None
        combined = 1.0
        for prob in probs:
            combined *= prob
        return combined

    @property
    def combined_probability_pct(self) -> float | None:
        combined = self.combined_probability
        return round(combined * 100, 1) if combined is not None else None

    @property
    def fair_decimal_odds(self) -> float | None:
        combined = self.combined_probability
        if not combined:
            return None
        return round(1.0 / combined, 2)

    @property
    def fair_american_odds(self) -> str:
        decimal = self.fair_decimal_odds
        if not decimal or decimal <= 1 or math.isinf(decimal):
            return "n/a"
        if decimal >= 2:
            return f"+{round((decimal - 1) * 100)}"
        return f"-{round(100 / (decimal - 1))}"


class ParlayLeg(models.Model):
    """One pick inside a parlay (a snapshot of the underlying prediction)."""

    parlay = models.ForeignKey(
        Parlay, on_delete=models.CASCADE, related_name="legs"
    )
    prediction = models.ForeignKey(
        MatchupPrediction,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="parlay_legs",
    )
    pick_label = models.CharField(max_length=200)
    match_label = models.CharField(max_length=200, blank=True)
    pick_probability = models.FloatField(null=True, blank=True)

    class Meta:
        ordering = ["pk"]

    def __str__(self) -> str:  # pragma: no cover - trivial
        return self.pick_label

    @property
    def pick_probability_pct(self) -> float | None:
        return round(self.pick_probability * 100, 1) if self.pick_probability else None
