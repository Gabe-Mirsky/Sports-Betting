def compact_team_text(value: object) -> str:
    """Return uppercase alphanumeric text for team matching."""

    return re.sub(r"[^A-Z0-9]", "", str(value).upper())


def normalize_team_abbr(value: object) -> str:
    """Normalize a team abbreviation, city, nickname, or full name."""

    compact = compact_team_text(value)
    if compact in TEAM_ALIASES:
        return TEAM_ALIASES[compact]
    if compact in CURRENT_TEAM_ABBRS:
        return compact
    return compact
